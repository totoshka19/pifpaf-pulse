/**
 * Когда опрашивать рилс в следующий раз.
 *
 * Просмотры растут по кривой с насыщением: взрыв первые двое суток, потом плато.
 * Опрашивать месячный рилс раз в час — платить за 24 одинаковых ответа в сутки.
 *
 * Расчёт бюджета в PLAN.md §7: адаптивная частота даёт ~520 результатов в месяц
 * против 43 200 при фиксированном часе, то есть укладывает нас в free tier Apify.
 * В ТЗ прямо сказано «бесплатки хватит» — это требование, а не пожелание.
 */

const HOUR = 3_600_000

/**
 * Возраст рилса в часах → интервал до следующего опроса в часах.
 * Первая подошедшая ступень выигрывает, поэтому порядок значим.
 */
const LADDER: readonly (readonly [maxAgeHours: number, intervalHours: number])[] = [
  [48, 1], //  младше двух суток — активный рост
  [24 * 7, 6], //  до недели — рост замедляется
  [24 * 30, 24], //  до месяца — почти плато
  [Infinity, 24 * 7], //  старше месяца — цифры практически заморожены
] as const

export function computeNextSyncAt(postedAt: Date | null, now: Date): Date {
  // Даты ещё нет (запись в статусе pending) или она из будущего из-за расхождения
  // часов — считаем рилс свежим и опрашиваем скоро.
  const ageHours =
    postedAt && postedAt.getTime() < now.getTime()
      ? (now.getTime() - postedAt.getTime()) / HOUR
      : 0

  const interval = LADDER.find(([maxAge]) => ageHours < maxAge)![1]

  return new Date(now.getTime() + interval * HOUR)
}
