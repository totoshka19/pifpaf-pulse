import { plural } from '@/lib/format/plural'
import type { ThrottleVerdict } from './throttle'

/**
 * Лимит «не чаще N в минуту на пользователя», PLAN.md §7.
 *
 * Часовой троттлинг на рилс не спасает от разгона: рилсов у блогера много,
 * и обойти его можно, просто чередуя их. Этот лимит ограничивает человека
 * целиком, независимо от того, по какому рилсу он жмёт.
 *
 * Пять в минуту: человек, осмысленно добавляющий ссылки, в них укладывается;
 * залипший на кнопке — нет.
 *
 * Не атомарный шлюз: «прочитать счётчик → сравнить» пропускает параллельные
 * запросы, читающие одно и то же значение. Это осознанно — жёсткий потолок
 * держит только месячный `tryReserve`, который атомарен сам по себе; здесь
 * лимит лишь снижает частоту обычного использования, не гонки.
 */
export const USER_SYNC_LIMIT = 5
export const USER_SYNC_WINDOW_MS = 60_000

export function checkUserRate(recentAttempts: number, _now: Date): ThrottleVerdict {
  if (recentAttempts < USER_SYNC_LIMIT) return { allowed: true }

  return {
    allowed: false,
    message:
      `Слишком часто. Больше ${USER_SYNC_LIMIT} ` +
      `${plural(USER_SYNC_LIMIT, ['обновления', 'обновлений', 'обновлений'])} ` +
      'в минуту не получится — подожди немного и попробуй снова',
  }
}
