import type { Usage } from '@/db/queries/budget'
import { formatDayMonthMsk } from '@/lib/format/date'

export type BudgetNotice = {
  headline: string
  detail: string
}

/**
 * Текст плашки «лимит обновлений исчерпан» — или `null`, если говорить не о чем.
 *
 * Вынесено из компонента в чистую функцию не ради красоты: считать здесь
 * приходится дату обнуления счётчика, а это переход через границу месяца и
 * года — ровно тот класс арифметики, который ломается молча и вылезает раз
 * в году. Компоненты в этом проекте юнит-тестами не покрываются (в
 * `vitest.config.mts` стоит `environment: 'node'` и берутся только `*.test.ts`),
 * значит внутри компонента эта арифметика осталась бы непроверенной.
 *
 * Порог — РОВНО ноль оставшихся. Предупреждать заранее значит пугать блогера
 * тем, чего ещё не случилось: последний результат потратится штатно и данные
 * придут. А `used > cap` (руками в базе, через `tryReserve` такое не пройдёт)
 * тоже считается исчерпанием — молчать там было бы худшим из вариантов.
 */
export function budgetNotice(usage: Usage): BudgetNotice | null {
  if (usage.left > 0) return null

  return {
    headline: 'Лимит обновлений на этот месяц исчерпан',
    detail:
      `Цифры ниже — те, что успели забрать. Новые обновления пойдут снова ` +
      `${formatDayMonthMsk(nextPeriodStart(usage.period))}, когда счётчик обнулится.`,
  }
}

/**
 * Первое число месяца, следующего за периодом счётчика.
 *
 * `period` — строка `YYYY-MM` (формат закреплён CHECK-ограничением
 * `ck_apify_usage_period`). Месяц в `Date.UTC` нумеруется с нуля, поэтому
 * `month` из строки уже и есть индекс СЛЕДУЮЩЕГО месяца — а переход через
 * декабрь `Date` разруливает сам, превращая тринадцатый месяц в январь
 * следующего года.
 *
 * Полночь берём московскую (UTC+3), а не UTC: счётчик живёт в московском
 * календаре, как и всё остальное время в интерфейсе.
 */
function nextPeriodStart(period: string): Date {
  const [year, month] = period.split('-').map(Number)
  return new Date(Date.UTC(year, month, 1, 0, 0, 0) - 3 * 3_600_000)
}
