import type { Session } from './session'

/**
 * Изоляция данных между кабинетами блогеров — прямое требование ТЗ
 * («разные аккаунты с разными рилсами»).
 *
 * Ключевое решение: чужая запись отдаётся как 404, а не 403.
 * 403 означает «оно есть, но тебе нельзя» — то есть подтверждает существование
 * записи. Перебирая идентификаторы, по разнице между 403 и 404 можно узнать,
 * какие рилсы вообще заведены в системе. Снаружи оба случая обязаны выглядеть
 * одинаково.
 */

export class NotFoundError extends Error {
  readonly status = 404

  constructor() {
    super('Не найдено')
    this.name = 'NotFoundError'
  }
}

/**
 * Пропускает запись, только если она принадлежит текущей сессии.
 *
 * Роль не учитывается намеренно: админ получает сводные цифры по всем блогерам
 * отдельным запросом лидерборда, но не сырые чужие записи через этот guard.
 */
export function assertOwned<T extends { userId: string }>(
  row: T | undefined | null,
  session: Session,
): T {
  if (!row || row.userId !== session.userId) throw new NotFoundError()
  return row
}
