/**
 * Подгружает .env.local для интеграционных тестов.
 *
 * Обычные юнит-тесты обходятся без него намеренно: если тест на чистую функцию
 * начинает требовать строку подключения, значит зависимости протекли туда,
 * где их быть не должно.
 */
try {
  process.loadEnvFile('.env.local')
} catch {
  // В CI переменные приходят из окружения, файла может не быть.
}

if (!process.env.DATABASE_URL_UNPOOLED && !process.env.DATABASE_URL) {
  throw new Error(
    'Интеграционным тестам нужна база. Заполни DATABASE_URL в .env.local — см. PLAN.md §13.',
  )
}
